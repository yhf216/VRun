"""Record installed helper dependencies and archive exact published copyleft sources.

Run after installing requirements. Downloads use official PyPI release metadata,
verify SHA256, and never execute downloaded build scripts.
"""
from concurrent.futures import ThreadPoolExecutor
import hashlib
import importlib.metadata as metadata
import json
from pathlib import Path
import urllib.request
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]


def distributions():
    found, todo = {}, ["pymobiledevice3"]
    while todo:
        distribution = metadata.distribution(todo.pop())
        name = distribution.metadata["Name"]
        if name in found:
            continue
        found[name] = distribution
        for value in distribution.requires or []:
            requirement = Requirement(value)
            if requirement.marker is None or requirement.marker.evaluate({"extra": ""}):
                todo.append(requirement.name)
    return found


def archive(item):
    name, distribution = item
    license_text = distribution.metadata.get("License-Expression") or distribution.metadata.get("License", "")
    classifiers = distribution.metadata.get_all("Classifier", [])
    entry = {"name": name, "version": distribution.version,
             "license": license_text[:100] if len(license_text) < 120 else "See bundled license text",
             "classifiers": [value for value in classifiers if "License" in value]}
    search = (license_text + " ".join(classifiers)).upper()
    if "GPL" in search or "GENERAL PUBLIC LICENSE" in search:
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{distribution.version}/json", timeout=60) as response:
            release = json.load(response)
        source = next(value for value in release["urls"] if value["packagetype"] == "sdist")
        destination = ROOT / "third_party/sources/ios17" / source["filename"]
        destination.parent.mkdir(parents=True, exist_ok=True)
        expected = source["digests"]["sha256"]
        if not destination.is_file() or hashlib.sha256(destination.read_bytes()).hexdigest() != expected:
            with urllib.request.urlopen(source["url"], timeout=90) as response:
                payload = response.read()
            if hashlib.sha256(payload).hexdigest() != expected:
                raise RuntimeError(f"Source checksum mismatch: {name}")
            destination.write_bytes(payload)
        entry["source"] = {"file": destination.name, "url": source["url"], "sha256": expected}
    return entry


def main():
    installed = distributions()
    with ThreadPoolExecutor(max_workers=4) as pool:
        entries = list(pool.map(archive, sorted(installed.items())))
    (ROOT / "third_party/ios17-dependencies.json").write_text(
        json.dumps({"pymobiledevice3": "11.44.0", "dependencies": entries}, indent=2), encoding="utf-8")
    (ROOT / "requirements-ios17.txt").write_text(
        "# iOS 17+ helper dependency snapshot; Windows x64 / Python 3.14.\n"
        "# Generated by scripts/archive_ios17.py from the validated conda base.\n"
        + "".join(f"{entry['name']}=={entry['version']}\n" for entry in entries), encoding="utf-8")
    license_file = next(Path(metadata.distribution("pymobiledevice3").locate_file(file))
                        for file in metadata.distribution("pymobiledevice3").files
                        if str(file).endswith("licenses/LICENSE"))
    (ROOT / "LICENSES/GPL-3.0.txt").write_bytes(license_file.read_bytes())
    print(f"Recorded {len(entries)} dependencies; archived copyleft source releases.")


if __name__ == "__main__":
    main()
